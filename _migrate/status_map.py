# 木桶口径的「未完成度」序（数值小者胜出）——
# ⚠️ **与显示序不是同一轴，勿合并**（技能 threshold-single-source-and-env-flag §一
#    「优先级不要掩盖重叠」）。此处只校验**同一集合**，不做顺序合并。
STATUS_ROLLUP_RANK = ("开发中", "待开发", "待规划", "已开发")


def require_known(seq, where="status_map"):
    """拒绝未登记状态（渲染前自检；**不静默回落**，红线 10「能拒绝才算校验」）。"""
    unknown = sorted(set(seq) - set(STATUS_ORDER))
    if unknown:
        raise ValueError(
            "%s：状态 %r 未登记到 STATUS_BADGE（已登记 %r）⇒ 拒绝生成，"
            "否则该状态会被**静默漏渲染**" % (where, unknown, STATUS_ORDER))
    return True


def check_status_keys(verbose=False):
    """自检：状态口径各处必须同轴。任一不满足即 `raise`（**不静默回落**）。

    拒绝条件：
      ① `STATUS` / `ROADMAP` / `PENDING` 里出现 `STATUS_ORDER` 未登记的状态；
      ② `STATUS_ROLLUP_RANK` 与 `STATUS_ORDER` 不是同一集合（缺一 / 多一）。
    注：`CLOSED_*` 组第二项是**自由文字**（留档说明），不是状态字段，不参与校验。
    """
    known = set(STATUS_ORDER)
    used = ({v[0] for v in STATUS.values()}
            | {r[1] for r in ROADMAP}
            | {p[1] for p in PENDING})
    unknown = sorted(used - known)
    if unknown:
        raise ValueError("状态 %r 未登记到 STATUS_BADGE（已登记 %r）⇒ 生成器会静默漏渲染"
                         % (unknown, STATUS_ORDER))
    if set(STATUS_ROLLUP_RANK) != known:
        raise ValueError("STATUS_ROLLUP_RANK 与 STATUS_ORDER 不同集合：%r vs %r"
                         % (STATUS_ROLLUP_RANK, STATUS_ORDER))
    unused = sorted(known - used)
    if verbose:
        print("[status_map] 状态口径自检 OK：used=%r / unused=%r" % (sorted(used), unused))
    return {"used": sorted(used), "unused": unused}


